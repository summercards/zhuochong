run () {
  local tag="$1"; shift
  env PYTHONHASHSEED=0 SKIP_RENDER=1 D18_ROLL_TRANSPORT=0 D18_ROLLWIN_OFF= \
      D18_LEGROLL_MAX=40 D18_FOOT_PIN_BLEND=8 D18_ARM_MIX_FROM=21 \
